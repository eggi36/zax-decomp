def file_batches():
    """Production file (name relative to reimpl/src) -> batch."""
    subsystem = {hexa(r['address']): r['subsystem'] for r in read_csv(DOCS / 'functions.csv')}
    votes = collections.defaultdict(collections.Counter)
    for r in read_csv(DOCS / 'reimpl.csv'):
        f = r['file']
        if not f.startswith('reimpl/src/'):
            continue
        votes[f[len('reimpl/src/'):]][BATCH_OF_SUBSYSTEM.get(subsystem.get(hexa(r['address']), ''), '6-4')] += 1
    batch = {f: c.most_common(1)[0][0] for f, c in votes.items()}
    for f in sorted(p.relative_to(SRC).as_posix() for p in SRC.rglob('*') if p.suffix in ('.cpp', '.h', '.inc', '.c')):
        if f in batch:
            continue
        name = Path(f).name
        if name in SHARED:
            batch[f] = '6-3'
        elif name in FILE_BATCH:
            batch[f] = FILE_BATCH[name]
        elif f.startswith(('libs/', 'libc/')):
            batch[f] = '6-4'
        elif name.endswith('_hooks.inc') and f.replace('_hooks.inc', '.cpp') in batch:
            batch[f] = batch[f.replace('_hooks.inc', '.cpp')]
        elif Path(f).with_suffix('.cpp').as_posix() in batch:
            batch[f] = batch[Path(f).with_suffix('.cpp').as_posix()]
    # headers and the rest: the batch of the production files that include them most
    includers = collections.defaultdict(collections.Counter)
    for p in SRC.rglob('*'):
        if p.suffix not in ('.cpp', '.h', '.inc', '.c'):
            continue
        f = p.relative_to(SRC).as_posix()
        if f not in batch:
            continue
        for line in p.read_text(encoding='latin-1').splitlines():
            if line.startswith('#include "'):
                inc = line.split('"')[1]
                includers[inc][batch[f]] += 1
    for _ in range(3):
        for f in sorted(p.relative_to(SRC).as_posix() for p in SRC.rglob('*') if p.suffix in ('.h', '.inc', '.cpp', '.c')):
            if f not in batch and includers.get(Path(f).name):
                batch[f] = includers[Path(f).name].most_common(1)[0][0]
    return batch


def layout(args):
    sys.path.insert(0, str(ROOT / 'tools'))
    import pefile
    import phase6_inventory as inv
    pe = pefile.PE(args.exe, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    secs = {s.Name.rstrip(b'\0').decode(): (base + s.VirtualAddress, s.Misc_VirtualSize, s.SizeOfRawData) for s in pe.sections}
    iat = pe.OPTIONAL_HEADER.DATA_DIRECTORY[12]
    want = {'.text': TEXT[0], '.rdata': RDATA[0], '.data': DATA[0]}
    for name, lo in want.items():
        if secs[name][0] != lo:
            sys.exit('section %s at 0x%x, expected 0x%x' % (name, secs[name][0], lo))
    if (base + iat.VirtualAddress, base + iat.VirtualAddress + iat.Size) != IAT or secs['.data'][0] + secs['.data'][2] != DATA[1] \
            or (secs['.data'][0] + secs['.data'][1] + 0xfff) & ~0xfff != BSS[1] or secs['.rdata'][0] + ((secs['.rdata'][1] + 0xfff) & ~0xfff) != RDATA[1]:
        sys.exit('the exe\'s section bounds differ from the constants of tools/exe_layout.py')

    batch = file_batches()
    uses, _ = inv.scan_sources()
    by_addr = collections.defaultdict(collections.Counter)
    unknown = set()
    for a, f, role, _no, _flags in uses:
        if role != 'prod':
            continue
        b = batch.get(f)
        if f in NOT_IN_EXE:
            continue
        if b is None:
            unknown.add(f)
            continue
        by_addr[a][b] += 1
    if unknown:
        print('files without a batch (their uses not counted): %s' % ' '.join(sorted(unknown)), file=sys.stderr)

    rows = []
    for r in read_csv(DOCS / 'phase6_inventory.csv'):
        if not r['address'].startswith('0x') or r['kind'].startswith('code') or r['kind'] in ('header', '.cms_t', '.cms_d'):
            continue
        a, size = hexa(r['address']), int(r['size'])
        sec = section_of(a)
        if sec is None or sec == '.text':
            continue
        rows.append(dict(address=a, size=size, section=sec, kind={'.rdata': 'rdata', '.data': 'data', '.bss': 'bss'}.get(r['kind'], r['kind']),
                         name=r['name']))
    for a, size, name in TEXT_DATA:
        rows.append(dict(address=a, size=size, section='.text', kind='text data', name=name))
    rows.sort(key=lambda r: r['address'])
    # tile: clip overlaps (an address inside a vtable or a region is a member of it), fill the gaps per section
    tiled = []
    for lo, hi, sec in ((TEXT_DATA[0][0], TEXT_DATA[0][0] + TEXT_DATA[0][1], '.text'), (IAT[0], IAT[1], 'IAT'),
                        (IAT[1], RDATA[1], '.rdata'), (DATA[0], DATA[1], '.data'), (BSS[0], BSS[1], '.bss')):
        rs = [r for r in rows if lo <= r['address'] < hi]
        pos = lo
        for i, r in enumerate(rs):
            if r['address'] > pos:
                tiled.append(dict(address=pos, size=r['address'] - pos, section=sec, kind='unnamed', name=''))
            r = dict(r, section=sec)
            size = max(r['size'], 1)
            if r['address'] < pos:
                # starts inside the previous row (an address the source names inside a vtable, e.g. a slot, or inside
                # a region): a member of it, in its block, up to at least the previous row's end. Until 2026-10-29
                # every row was clipped at the next row's start, which cut 0x5ec170's 79 slots at slot 43 (0x5ec21c,
                # named by ui_label.cpp) into a block of its own; the trial with own blocks faulted on it
                r['kind'] = 'member'
                prev = tiled[-1]
                size = max(size, pos - r['address'])
                prev['size'] = r['address'] - prev['address']
            r['size'] = min(size, hi - r['address'])
            tiled.append(r)
            pos = r['address'] + r['size']
        if pos < hi:
            tiled.append(dict(address=pos, size=hi - pos, section=sec, kind='unnamed', name=''))
    # owners
    for r in tiled:
        c = by_addr.get(r['address'], collections.Counter())
        cc = collections.Counter({k: v for k, v in c.items() if k != '6-3'})
        r['owner'] = (cc or c).most_common(1)[0][0] if c else ''
        r['users'] = ' '.join(sorted(c))
    # blocks
    # the old homes: by the old row that holds the new row's start (since batch 6-10a; before only by an equal address,
    # so a row the regeneration starts elsewhere lost its home)
    old_rows = sorted((hexa(r['address']), int(r['size']), r['home'], hexa(r['block'])) for r in read_csv(LAYOUT)) if LAYOUT.exists() else []
    old_starts = [a for a, *_ in old_rows]

    def old_row(a):
        i = bisect.bisect_right(old_starts, a) - 1
        return old_rows[i] if i >= 0 and a < old_rows[i][0] + max(old_rows[i][1], 1) else None
    block = None
    for r in tiled:
        # since batch 6-8: the unnamed row at the start of .bss is the tail of the .data table before it (the mode table
        # span rows C 0x62ef18, 256 dwords up to 0x62f318) and stays in its block, so the table is one definition
        # (its .bss bytes are zero in the block's initial bytes)
        bss_tail = r['address'] == BSS[0] and r['kind'] == 'unnamed' and block is not None and block['section'] == '.data'
        span = next((o for o in OBJECTS if o[0] <= r['address'] < o[1]), None)
        if span and r['address'] + r['size'] > span[1]:
            sys.exit('row 0x%x runs over the end of the object 0x%x-0x%x' % (r['address'], span[0], span[1]))
        if span and r['address'] > span[0]:
            new = False   # a part of an object that starts in an earlier row (OBJECTS, since batch 6-10b)
        elif span:
            new = True
        else:
            new = (block is None or r['kind'] == 'vtable' or block['kind'] == 'vtable' and r['kind'] not in ('member',)
                   or (r['section'] == 'IAT') != (block['section'] == 'IAT') or r['section'] != block['section'] and not bss_tail
                   or (r['owner'] and block['owner'] and r['owner'] != block['owner'] and r['kind'] != 'member'
                       and r['section'] != 'IAT'))
            if block is not None and any(o[0] <= block['address'] < o[1] for o in OBJECTS):
                new = True   # the row after an object
        if new:
            block = dict(address=r['address'], kind=r['kind'], section=r['section'], owner=r['owner'], users=set())
            if r['section'] == 'IAT':
                block['owner'] = '6-9'   # one table: moved as a whole once every user is converted (the system layer)
        if not block['owner'] and r['owner']:
            block['owner'] = r['owner']
        block['users'] |= set(r['users'].split())
        r['block'] = block
    # homes: a block keeps the home its rows had. A block whose rows had different homes, or that holds part of an old
    # own block (the old block split: code that indexes from one part into the other would leave our definition),
    # becomes `image` and is reported (the batch that moves it checks it again); a block that joins whole old own
    # blocks stays own (one definition instead of several) and is reported
    members = collections.defaultdict(list)
    for r in tiled:
        o = old_row(r['address'])
        r['old_home'], r['old_block'] = (o[2], o[3]) if o else ('image', None)
        members[r['block']['address']].append(r)
    old_block_rows = collections.Counter(b for *_, b in old_rows)
    new_of_old = collections.defaultdict(set)
    for r in tiled:
        new_of_old[r['old_block']].add(r['block']['address'])
    changed, joined = [], []
    for a, rs in members.items():
        homes = {r['old_home'] for r in rs}
        home = homes.pop() if len(homes) == 1 else 'mixed'
        olds = {r['old_block'] for r in rs}
        split = any(len(new_of_old[ob]) > 1 for ob in olds)
        if home == 'own' and split:
            home = 'image'
            changed.append((a, 'part of a split own block'))
        elif home == 'own' and len(olds) > 1:
            joined.append((a, sorted(olds)))
        elif home == 'mixed':
            home = 'image'
            changed.append((a, 'rows of own and image blocks'))
        for r in rs:
            r['home'] = home
    with open(LAYOUT, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS, lineterminator='\n')
        w.writeheader()
        for r in tiled:
            b = r['block']
            w.writerow(dict(address='0x%x' % r['address'], size=r['size'], section=r['section'], kind=r['kind'],
                            block='0x%x' % b['address'], name=r['name'], owner=b['owner'] or ('6-9' if b['section'] == 'IAT' else '6-4'),
                            users=' '.join(sorted(b['users'])), home=r['home']))
    for a, why in changed:
        print('block 0x%x set to image: %s' % (a, why), file=sys.stderr)
    for a, olds in joined:
        print('own block 0x%x joins the old own blocks %s' % (a, ' '.join('0x%x' % b for b in olds)), file=sys.stderr)
    blocks = {}
    for r in tiled:
        blocks.setdefault(r['block']['address'], r['block'])
    print('%d rows, %d blocks' % (len(tiled), len(blocks)))
    by_owner = collections.Counter()
    for b in blocks.values():
        by_owner[b['owner'] or '-'] += 1
    print('blocks by owner: %s' % ', '.join('%s %d' % kv for kv in sorted(by_owner.items())))
    shared = sum(1 for b in blocks.values() if len(b['users'] - {'6-3'}) > 1)
    print('blocks named by more than one batch: %d' % shared)


# ---- tables ---------------------------------------------------------------------------------------------------------

def load_blocks():
    """Blocks of docs/exe_layout.csv: address -> dict(size, section, kind, home, owner)."""
    blocks = {}
    for r in read_csv(LAYOUT):
        b = blocks.setdefault(hexa(r['block']), dict(address=hexa(r['block']), size=0, section=r['section'], kind=r['kind'],
                                                     home=r['home'], owner=r['owner'], rows=[]))
        if r['home'] != b['home']:
            sys.exit('docs/exe_layout.csv: block %s has rows with home %s and %s' % (r['block'], b['home'], r['home']))
        b['size'] += int(r['size'])
        b['rows'].append(r)
    return blocks


def tables(args):
    out = Path(args.out)
    fns = sorted({hexa(r['address']) for r in read_csv(DOCS / 'reimpl.csv')
                  if TEXT[0] <= hexa(r['address']) < TEXT[1]})
    blocks = load_blocks()
    vts = sorted(b['address'] for b in blocks.values() if b['kind'] == 'vtable')
    own = sorted(a for a, b in blocks.items() if b['home'] == 'own')
    lines = ['// Generated by tools/exe_layout.py tables from docs/reimpl.csv and docs/exe_layout.csv: the keys of the',
             '// address layer (reimpl.h). Addresses only.',
             '#pragma once',
             'namespace zax::layer {',
             'inline constexpr int FN_COUNT = %d;' % len(fns),
             'inline constexpr DWORD FN[FN_COUNT] = {']
    for i in range(0, len(fns), 12):
        lines.append('    ' + ', '.join('0x%x' % a for a in fns[i:i + 12]) + ',')
    lines += ['};',
              'inline constexpr int VT_COUNT = %d;' % len(vts),
              'inline constexpr DWORD VT[VT_COUNT] = {']
    for i in range(0, len(vts), 12):
        lines.append('    ' + ', '.join('0x%x' % a for a in vts[i:i + 12]) + ',')
    lines += ['};',
              'inline constexpr DWORD TEXT_START = 0x%x, TEXT_END = 0x%x;' % TEXT,
              'inline constexpr DWORD IAT_START = 0x%x, IAT_END = 0x%x;' % IAT,
              'inline constexpr DWORD DATA_START = 0x%x, DATA_END = 0x%x;   // .rdata after the IAT ... .bss' % (IAT[1], BSS[1]),
              'inline constexpr DWORD TEXT_DATA[][2] = {%s};' % ', '.join('{0x%x, %d}' % (a, n) for a, n, _ in TEXT_DATA),
              '}  // namespace zax::layer',
              '#ifdef ZAX_STANDALONE',
              '// The blocks whose home is our own definition (generated by tools/extract_exe_data.py into the exe build)']
    for a in own:
        lines.append('extern "C" BYTE zax_block_%x[0x%x];' % (a, blocks[a]['size']))
    lines += ['namespace zax::layer {',
              'struct OwnBlock {',
              '    DWORD address, size;',
              '    BYTE *own;',
              '};',
              'inline constexpr int OWN_COUNT = %d;' % len(own),
              'inline constexpr OwnBlock OWN[OWN_COUNT + 1] = {']
    for a in own:
        lines.append('    {0x%x, 0x%x, zax_block_%x},' % (a, blocks[a]['size'], a))
    lines += ['    {0xffffffff, 0, nullptr},', '};', '}  // namespace zax::layer', '#endif', '']
    (out / 'addr_layer.inc').write_text('\n'.join(lines), encoding='utf-8')
    # The C runtime of the libraries (src/libc, C without the layer's templates; since batch 6-4): the function table's
    # index of every address its ZAX_CRT/ZAX_CRT_ADDR calls name, for the standalone exe's ZAX_CRT
    index = {a: i for i, a in enumerate(fns)}
    named = set()
    for h in sorted((SRC / 'libc').rglob('*.h')):
        for m in re.finditer(r'ZAX_CRT(?:_ADDR)?\((?:[^;]*?,\s*)?(0x[0-9a-f]{6})\)', h.read_text(encoding='latin-1')):
            named.add(int(m.group(1), 16))
    c = ['/* Generated by tools/exe_layout.py tables from docs/reimpl.csv: the function table index of the addresses',
         ' * src/libc calls (zax_libc.h, ZAX_CRT). Addresses only. */', '#pragma once']
    c += ['#define ZAX_FN_INDEX_0x%x %d' % (a, index[a]) for a in sorted(named) if a in index]
    (out / 'addr_layer_c.h').write_text('\n'.join(c) + '\n', encoding='utf-8')
    print('addr_layer.inc: %d functions, %d vtables, %d own blocks; addr_layer_c.h: %d' % (len(fns), len(vts), len(own), len(named)))


