#!/usr/bin/env python3
"""The address layer's layout (docs/DECOMPILATION.md 13, "Batch 6-3: the address layer").

Two steps:

  layout   writes docs/exe_layout.csv: the data of Zax.exe the reimplementation still takes from the exe (.rdata with
           the vtables and the IAT, the initialised .data, .bss, the one table in .text), tiled without gaps into rows
           (the regions of docs/phase6_inventory.csv plus the unnamed gaps between them) and the rows grouped into
           blocks: a vtable is a block, the IAT is one block, otherwise a run of neighbouring rows with the same owner
           (the rows nobody in the production code names go with the block before them, so a block keeps the
           internal layout the code indexes across). Owner: the phase 6 batch (6-4 ... 6-9) whose production files
           name the row most; users: every batch whose files name it. The column `home` (image or own) is the state
           the migration batches change; regenerating keeps it per row (by the old row that holds the row's start; a
           block of mixed or split homes becomes image and is reported). Addresses and names only, never the
           exe's bytes. Needs the venv (capstone and pefile through tools/phase6_inventory.py) and the exe for the
           section bounds.

  tables OUT
           writes OUT/addr_layer.inc for reimpl.h (both builds, at build time; only the standard library): the sorted
           addresses of docs/reimpl.csv (the function table's keys), the vtables, the data sections' bounds and the
           blocks whose home is `own` (the standalone exe's own definitions, tools/extract_exe_data.py).

    .venv/bin/python -I tools/exe_layout.py layout [--exe "$(python3 -I tools/game_paths.py exe)"]
    python3 -I tools/exe_layout.py tables OUTDIR
"""
