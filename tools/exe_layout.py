def read_csv(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def hexa(s):
    return int(s, 16)


def section_of(a):
    if IAT[0] <= a < IAT[1]:
        return 'IAT'
    for name, (lo, hi) in (('.text', TEXT), ('.rdata', RDATA), ('.data', DATA), ('.bss', BSS)):
        if lo <= a < hi:
            return name
    return None


