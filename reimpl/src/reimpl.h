// Shared basics of the reimplementation: logging, hooks, x87 helpers.
//
// The reimplementation runs as Zax-Reimpl.dll inside the original Zax.exe (loaded by the launcher
// before the exe starts). Every reimplemented function replaces the original with a jump at its
// entry point. As long as old and new code run side by side, memory layout and calling conventions
// must match the original (MSVC 6, 32 bit). That is why it is built with clang's MSVC ABI
// (i386-pc-windows-msvc): vtables, destructors, struct layout and calling conventions as in VC++.
