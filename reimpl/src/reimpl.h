// Addresses known only at run time (tables of addresses): the same, looked up at run time; an address the layer does
// not know is the image's (as at<>)
#ifdef ZAX_STANDALONE
template <typename F> inline F fn_dyn(DWORD a)
{
    const int i = layer::find(layer::FN, a);
    return i < 0 ? at<F>(a) : reinterpret_cast<F>(static_cast<uintptr_t>(layer::zax_fn_table[i]));
}
template <typename T> inline T glob_dyn(DWORD a)
{
    BYTE *own = layer::own_of(a);
    return own ? reinterpret_cast<T>(own) : at<T>(a);
}
inline DWORD glob_addr_dyn(DWORD a) { return (DWORD)(uintptr_t)glob_dyn<BYTE *>(a); }
// A code value known only at run time (since batch 6-10c): the function table's entry for the exe address of a
// reimplemented function, anything else (a value that already is one) as it is; for helpers that hand a function on
// (atexit, qsort, the vector constructors)
inline DWORD fn_addr_dyn(DWORD a)
{
    const int i = layer::find(layer::FN, a);
    return i < 0 ? a : layer::zax_fn_table[i];
}
// The other way: the exe address an address of our own blocks stands for (anything else as it is), for tooling that
// compares runs by the exe's addresses (replay.cpp's frame hashes of the parts' vtables)
inline DWORD exe_address_of(DWORD p)
{
    for (int i = 0; i < layer::OWN_COUNT; i++) {
        const DWORD own = (DWORD)(uintptr_t)layer::OWN[i].own;
        if (p >= own && p < own + layer::OWN[i].size)
            return layer::OWN[i].address + (p - own);
    }
    return p;
}
// The exe address a code value stands for (a function table entry, since batch 6-10b our replacement), anything else as
// it is; for tooling that reads the exe's code behind a slot (replay.cpp's class kinds). A linear search: cache it.
inline DWORD exe_code_of(DWORD p)
{
    for (int i = 0; i < layer::FN_COUNT; i++)
        if (layer::zax_fn_table[i] == p)
            return layer::FN[i];
    return p;
}
#else
inline DWORD exe_address_of(DWORD p) { return p; }
inline DWORD exe_code_of(DWORD p) { return p; }
template <typename F> inline F fn_dyn(DWORD a) { return reinterpret_cast<F>(static_cast<uintptr_t>(a)); }
template <typename T> inline T glob_dyn(DWORD a) { return reinterpret_cast<T>(static_cast<uintptr_t>(a)); }
inline DWORD glob_addr_dyn(DWORD a) { return a; }
inline DWORD fn_addr_dyn(DWORD a) { return a; }
#endif
inline DWORD vt_dyn(DWORD a) { return glob_addr_dyn(a); }

// v with its low byte replaced by b, as `mov al, byte ptr [...]` leaves eax. In asm because clang 22 compiles
// (v & ~0xff) | load8(p) to one movzbl (the upper bytes lost) when v also forms the byte's address (found 2026-10-25
// with DefinitionList::InUse; the audit of every byte merge of reimpl/src: docs/DECOMPILATION.md section 13, "Batch
// section-12 leftovers"). Use it for every such merge whose byte comes from memory addressed through v.
inline DWORD with_low_byte(DWORD v, BYTE b)
{
    __asm__("movb %1, %b0" : "+q"(v) : "qm"(b));
    return v;
}

// Code values in assembler text (since batch 6-10c). In the DLL the exe address itself, as before. In the standalone exe
// a dword cell `_zax_code_<address>` (tools/extract_exe_data.py makes one for every ZAX_ASM_CODE*(address) of the
// sources) in the section .zaxcv, and every dword of .zaxcv (also the generated modules' tables of call targets,
// ZAX_ASM_CODE_VALUES) holds an exe address that the start replaces by the function table's entry (fn_addr_dyn):
//   ZAX_ASM_PUSH_CODE(a)    intel syntax: push the code value
//   ZAX_ASM_CODE_ATT(a)     AT&T syntax: the value as an operand of movl/pushl ($a, or the cell)
//   ZAX_ASM_CODE_VALUES     the section of a generated module's table of call targets (.data in the DLL)
#ifdef ZAX_STANDALONE
#define ZAX_ASM_PUSH_CODE(a) "push dword ptr [_zax_code_" #a "]"
#define ZAX_ASM_CODE_ATT(a) "_zax_code_" #a
#define ZAX_ASM_CODE_VALUES "\n    .section .zaxcv$m,\"dw\"\n"
#else
#define ZAX_ASM_PUSH_CODE(a) "push " #a
#define ZAX_ASM_CODE_ATT(a) "$" #a
#define ZAX_ASM_CODE_VALUES "\n    .data\n"
#endif

// A hook: original address, replacement, the first bytes of the original (guards against a different
// exe) and the length of the whole instructions the jump overwrites (>= 5, no relative jumps/calls).
// Those instructions are copied into a trampoline that keeps the original callable (self-tests);
// length 0 means no trampoline. A relative call (e8) among them is allowed if call_at names its offset
// + 1; the trampoline then gets the corrected target.
struct Hook {
    DWORD address;
    void *replacement;
    const char *name;
    unsigned char length;
    unsigned char expected[8];
    unsigned char call_at = 0;
};

// Address of a function or member function (for member function pointers the first part)
template <typename F> inline void *ptr(F f)
{
    void *p;
    memcpy(&p, &f, sizeof p);
    return p;
}

// Hook table of a module: ZAX_HOOKS(module) { const Hook list[] = {...}; return emit_hooks(out, list); }
// in the module's .cpp. build.sh collects all tables into hook_tables.inc, so a new module does not
// touch main.cpp. Called twice: with out == nullptr for the count, then to copy the entries.
#define ZAX_HOOKS(module) int hooks_##module(Hook *out)
template <int N> inline int emit_hooks(Hook *out, const Hook (&list)[N])
{
    if (out)
        memcpy(out, list, sizeof list);
    return N;
}

// Callable original of a function: its trampoline when hooked, otherwise the function itself
void *original_address(DWORD address);
template <typename T> inline T original(DWORD address) { return reinterpret_cast<T>(original_address(address)); }
// The original of a path that never runs in the game (the C runtime's code for a locale other than "C" or multibyte
