// x87 comparisons as in the original (fcom + test ah, 1 or 0x41): "unordered" (NaN) counts as less.
inline bool x87_lt(long double a, long double b) { return !(a >= b); }
inline bool x87_le(long double a, long double b) { return !(a > b); }

// fistp with the FPU's current rounding mode (default: to nearest, ties to even)
inline int x87_fistp(long double v)
{
    int r;
    __asm__("fistpl %0" : "=m"(r) : "t"(v) : "st");
    return r;
}

// __ftol of the C runtime (0x5d0488): truncate to 64 bit with fistp, the low 32 bits
inline int x87_ftol(long double v)
{
    WORD cw, chop;
    long long r;
    __asm__ volatile("fnstcw %0" : "=m"(cw));
    chop = cw | 0x0c00;
    __asm__ volatile("fldcw %1\n\tfistpll %0\n\tfldcw %2" : "=m"(r) : "m"(chop), "m"(cw), "t"(v) : "st");
    return (int)r;
}

// Round a value to float, like fstp dword ptr
inline long double to_float(long double v) { return (long double)(float)v; }

// A value that goes to a float in memory and is read back, like fstp dword ptr and fld dword ptr. The optimizer
// turns (float)((long double)a * b) of two floats into a float instruction, which on the x87 stays unrounded in
// its register; a store it cannot remove keeps the rounding of the original.
inline float float_in_memory(long double v)
{
    volatile float t = (float)v;
    return t;
}

