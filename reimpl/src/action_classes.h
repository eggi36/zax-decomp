// Class registration of the action classes of Zax.exe (phase 3, game logic): CAction's class getter
// (0x41a650) and constructor (0x41a6b0), and for the 56 classes of the action file 0x4b8000-0x4c7fff
// (CMultipleActionsAction to CShakeScreenAction, plus the helper SyfaceTypeSoundItem (sic) of
// CPlaySoundBySurfaceTypeAction and CSendWeaponDischargedMessage) their Create, CreateArray,
// RegisterFields and the stand-alone class getters; CSwitchMapActionBase's constructor (0x4c0fa0) and
// CPainAction's constructor with values (0x4c3c20). Since 2026-10-25 also the 7 classes of 0x4b62d0-
// 0x4b7fff (CRemoveVelocityAction, CDelayAction, COnlyOnceAction, COnlyOnceEveryXSecondsAction,
// CImpersonateAction, CWhileAction, CRepeatAction) and the copies of the class getters in the vtables
// (slot 2) of the 32 classes 0x4b62d0-0x4bffff. Since 2026-10-25 too: the slot 2 copies of the 31
// classes 0x4c0000-0x4c7fff and the registration of the classes 0x41b000-0x41ffff (CConditionalAction,
// CIfAction, CActionQueueItem, CActionQueue, CDialogActionBase, CDialogLine, COtherMapAction,
// CTriggerRelayAction's Create and CreateArray). The behaviour (the virtual slots: execute, the
// destructors, ...) is in action_slots.cpp, action_slots2.cpp and action_helpers.cpp.
//
// Every action starts with the CObject part {vtable, dynamic properties}; CAction (8 bytes, abstract,
// class 0x62e770, vtable 0x5ece50) adds nothing and registers no fields (RegisterFields 0x58ea40 is a
// single ret). A class's constructor is inlined into its Create and CreateArray: CAction's constructor
// (CObject's, vtable 0x5ece50, Object_InitFields), then one level per class down to the created one,
// each the members' constructors (ZStrings; CShakeScreenAction's embedded CLengthEnvelope), the
// class's vtable and Object_InitFields again (the field defaults through the class of that vtable).
// The class getters are inlined into RegisterFields as well; the registration's parameters are the
// same in every copy [verified: the zero paths of all copies, tools of this batch].
//
// Layouts and fields: docs/fields.csv (offsets and names) [confirmed: constructors and RegisterFields
// of the exe]; the descriptors registered at startup are compared with the reimplementation's in the
// checks (checks_action_classes.cpp).
